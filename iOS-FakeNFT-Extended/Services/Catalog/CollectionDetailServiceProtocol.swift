import Foundation

/// Протокол для загрузки детальных данных коллекции: NFT и автора.
///
/// Отвечает за асинхронную загрузку списка NFT по идентификаторам
/// и информации об авторе коллекции. Используется в `CollectionDetailViewModel`.
/// Помечен `Sendable` для безопасной передачи между actor-сервисами
/// и `@MainActor` ViewModel.
///
/// Имя и сайт автора приходят в составе `NftCollection` (поля `author` и `website`),
/// отдельная ручка `/users/{id}` mock-сервером не используется, поэтому `Author`
/// собирается в `CollectionDetailViewModel` из переданной коллекции синхронно.
protocol CollectionDetailServiceProtocol: Sendable {

    /// Загружает список NFT по переданным идентификаторам.
    ///
    /// Реализация **best-effort**: если часть NFT не загрузилась, в ответ
    /// попадают только успешно загруженные. Метод бросает ошибку только если
    /// **все** запросы упали (или массив `ids` непустой, но успехов нет).
    ///
    /// Дубликаты в `ids` дедуплицируются — для одного id делается не более одного
    /// сетевого запроса. Порядок NFT в результате не гарантируется и может отличаться
    /// от порядка в `ids`.
    ///
    /// - Parameter ids: Массив уникальных идентификаторов NFT (могут содержать дубликаты).
    /// - Returns: Массив загруженных NFT в порядке переданных `ids`. Может быть короче `ids`.
    /// - Throws: Ошибка, если ни один NFT не удалось загрузить.
    func loadNfts(byIds ids: [String]) async throws -> [Nft]

    /// Сбрасывает внутренний кэш загруженных NFT.
    /// Вызывается из ViewModel при pull-to-refresh.
    func invalidateCache() async
}
