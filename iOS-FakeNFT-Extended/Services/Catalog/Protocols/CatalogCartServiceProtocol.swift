import Foundation

/// Протокол сервиса корзины, используемого эпиком Каталога.
///
/// Автономный от потенциальных протоколов эпика Корзины: каждый эпик
/// разрабатывается параллельно и владеет своими сервисами. Это позволяет
/// избежать гонки за общий тип в shared-зоне между эпиками.
///
/// Реализуется как `actor`, безопасен для конкурентного доступа из ViewModel.
protocol CatalogCartServiceProtocol: Sendable {

    /// Загружает текущий состав корзины пользователя с сервера.
    ///
    /// Использует in-memory кэш — повторный вызов не делает сетевой запрос
    /// пока кэш не инвалидирован.
    func loadCart() async throws -> Set<String>

    /// Заменяет состав корзины на сервере и возвращает обновлённое множество
    /// из ответа сервера.
    ///
    /// Сервер заменяет всё множество nft, не диффом. Поэтому передаваемый
    /// `ids` должен содержать **все** id, которые останутся в корзине.
    ///
    /// **Ограничение:** пустой `ids` не очищает корзину на сервере
    /// (особенность mock API). См. `OrderSetNftsRequest` для подробностей.
    func setCart(_ ids: Set<String>) async throws -> Set<String>

    /// Сбрасывает кэш. Следующий `loadCart` сделает сетевой запрос.
    func invalidateCache() async
}
