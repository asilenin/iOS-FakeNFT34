import Foundation

/// Протокол сервиса избранного, используемого эпиком Каталога.
///
/// Автономный от `Services/Shared/FavoritesServiceProtocol`: каждый эпик
/// разрабатывается параллельно и владеет своими сервисами. Это позволяет
/// избежать гонки за общий тип в shared-зоне между эпиками.
///
/// Реализуется как `actor`, безопасен для конкурентного доступа из ViewModel.
protocol CatalogFavoritesServiceProtocol: Sendable {

    /// Загружает текущий набор лайков пользователя с сервера.
    ///
    /// Использует in-memory кэш — повторный вызов не делает сетевой запрос
    /// пока кэш не инвалидирован.
    func loadFavorites() async throws -> Set<String>

    /// Заменяет набор лайков на сервере и возвращает обновлённое множество
    /// из ответа сервера.
    ///
    /// Сервер заменяет всё множество лайков, не диффом. Поэтому передаваемый
    /// `ids` должен содержать **все** id, которые останутся лайкнутыми.
    ///
    /// **Ограничение:** пустой `ids` не очищает лайки на сервере (особенность
    /// mock API). Возвращённое множество будет тем же, что и до запроса.
    /// Это ограничение принято — обходить не пытаемся в P3.
    func setFavorites(_ ids: Set<String>) async throws -> Set<String>

    /// Сбрасывает кэш. Следующий `loadFavorites` сделает сетевой запрос.
    func invalidateCache() async
}
