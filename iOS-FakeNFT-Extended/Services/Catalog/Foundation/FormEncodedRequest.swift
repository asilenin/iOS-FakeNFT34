import Foundation

/// Маркерный протокол для запросов, тело которых сериализуется как
/// `application/x-www-form-urlencoded`.
///
/// `CatalogNetworkClient` распознаёт реквесты этого типа через cast и
/// строит body иначе, чем для обычных JSON-реквестов.
///
/// Имена полей рекомендуется хранить в private enum внутри каждого
/// конкретного реквеста, чтобы избежать опечаток в строковых ключах

protocol FormEncodedRequest: NetworkRequest {
    /// Поля для form-кодирования.
    ///
    /// Каждый ключ → массив значений:
    /// - 1 элемент → одна пара `key=value`,
    /// - N элементов → повторяющиеся пары `key=v1&key=v2`,
    /// - **пустой массив** → ключ **не отправляется** в body
    ///   (особенность mock-сервера FakeNFT: `key=` интерпретируется
    ///   как значение и ломает запрос с `entity by id is missing`).
    var formFields: [String: [String]] { get }
}
