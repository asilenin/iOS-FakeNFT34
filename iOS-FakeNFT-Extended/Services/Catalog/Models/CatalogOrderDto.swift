import Foundation

/// Минимальная DTO заказа (корзины) пользователя, нужная эпику Каталога.
///
/// API `/orders/1` возвращает `{ nfts: [String], id: String }`.
/// `nfts` — массив id NFT в корзине; именно ими оперирует эпик Каталога
/// при добавлении/удалении из корзины.
///
/// Сосуществует с потенциальной полной моделью `Order`, которую может
/// объявить эпик Корзины — наша DTO независима, чтобы избежать конфликтов
/// между параллельно разрабатываемыми эпиками.
struct CatalogOrderDto: Decodable {
    let id: String
    let nfts: [String]
}
