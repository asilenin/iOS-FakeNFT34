import Foundation

/// Минимальная DTO профиля пользователя, нужная эпику Каталога.
///
/// API `/profile/1` возвращает много полей (`name`, `avatar`, `description`,
/// `website`, `nfts`, `likes`, `id`). Каталогу нужны только `likes` и `id`
/// для своих сервисов; остальные поля игнорируются при декодировании.
///
/// Сосуществует с потенциальной полной моделью `Profile`, которую может
/// объявить эпик Профиля — наша DTO независима, чтобы избежать конфликтов
/// между параллельно разрабатываемыми эпиками.
struct CatalogProfileDto: Decodable {
    let id: String
    let likes: [String]
}
