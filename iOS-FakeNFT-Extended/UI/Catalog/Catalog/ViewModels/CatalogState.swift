import Foundation

/// Состояние загрузки каталога коллекций.
///
/// Отслеживает статус операции загрузки данных с сервера.
/// Данные (коллекции) хранятся отдельно в ViewModel для разделения ответственности.
enum CatalogState {
    /// Идёт загрузка коллекций с сервера.
    case loading
    
    /// Коллекции успешно загружены.
    case success
    
    /// Произошла ошибка при загрузке; детали доступны в `CatalogViewModel.error`.
    case error
}
